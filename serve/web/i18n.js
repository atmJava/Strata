  const saved = store.get("lang", "");
  const guessed = String(navigator.language || "en").toLowerCase().split("-")[0] === "zh" ? "zh" : "en";
  let lang = saved === "en" || saved === "zh" ? saved : guessed;

  function t(key, subs) {
    const e = D[key];
    let s = e ? (e[lang] || e.en) : key;
    if (subs) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in subs ? String(subs[k]) : m));
    return s;
  }
  t.has = (key) => !!D[key];

  // words in the HTML: data-i18n replaces the element's own text (its child elements stay), the other
  // data-i18n-* attributes fill title / aria-label / placeholder.
  function apply(root) {
    const doc = root || document;
    for (const el of doc.querySelectorAll("[data-i18n]")) {
      const text = [...el.childNodes].filter((n) => n.nodeType === 3 && n.nodeValue.trim() !== "");
      if (text.length) {
        text[0].nodeValue = t(el.dataset.i18n);
        for (const n of text.slice(1)) n.nodeValue = "";
      }
    }
    for (const el of doc.querySelectorAll("[data-i18n-title]")) el.setAttribute("title", t(el.dataset.i18nTitle));
    for (const el of doc.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
    for (const el of doc.querySelectorAll("[data-i18n-placeholder]")) el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  }
  function paintBtn() {
    const b = document.getElementById("lang-btn");
    if (!b) return;
    b.textContent = lang === "zh" ? "EN" : "\u4e2d\u6587";          // the other language's own name
    b.setAttribute("title", t("lang.title"));
    b.setAttribute("aria-label", t("lang.title"));
  }
  function setLang(next) {
    lang = next;
    store.set("lang", next);
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    apply(document);
    paintBtn();
    window.dispatchEvent(new Event("strata:lang"));               // the app re-renders what JS drew
  }
  function boot() {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    apply(document);
    paintBtn();
    const b = document.getElementById("lang-btn");
    if (b) b.onclick = () => setLang(lang === "zh" ? "en" : "zh");
  }
  if (document.readyState !== "loading") boot();
  else document.addEventListener("DOMContentLoaded", boot);

  window.STRATA_I18N = {get lang() { return lang; }, t, apply, setLang};
  window.t = (k, s) => window.STRATA_I18N.t(k, s);
  window.t.has = (k) => window.STRATA_I18N.t.has(k);
