#!/usr/bin/env python3
"""The bitwise gate for a kernel or layout change, in one self-contained script.

Why this exists: the harness this box used for the bitwise gate read its prompt from /tmp/parity.py,
and /tmp gets cleared - so run-arm.sh kept printing a completed arm log while the correctness gate
silently stopped running.  Nothing was wrong with the engine; the gate had just evaporated.

This version carries its own prompt (generated by a formula, so it is the same prompt on every run
and on every machine), pins temperature 0, and hashes the reasoning and the answer separately so a
change that only moves the thinking is visible.  It prints draft_n / draft_n_accepted too, because on
this box a difference in draft acceptance is often the first sign that something moved.

Read the result honestly:
  - Run it in the gate config the upstream docs ask for (single slot, --pcie-frac 0, adaptive off,
    STRATA_IQ_MT_MIN=1): in this box's production shape (4 slots, --pcie-frac 0.31, adaptive) the
    output is not reproducible at all, so a hash difference there proves nothing.
  - Run it several times per arm, including a cold start, and report the count (e.g. 9 of 10), not a
    single pair.
  - --spec cannot be turned off on a native pack (it wants --spec T, T >= 2), so what you are gating
    is a spec window, not a plain decode.

Usage: parity_window.py [label] [context-lines] [max-tokens]   (default arm 200 lines 512 tokens)
       PARITY_EFFORT=high|medium|low|off   reasoning effort to pin (default off: the answer is what
                                           the kernels produce; thinking adds a second, noisier hash)
"""
import hashlib
import json
import os
import subprocess
import sys
import time
import urllib.request

BASE = "http://127.0.0.1:8080"
CFG = "/opt/ai/src/strata-0.2.2/strata-022.json"
MODEL = "qwen3.8-flash-next-iq3_xxs-abliterated"


def api_key():
    try:
        return json.load(open(CFG)).get("api_key", "")
    except Exception:
        return os.environ.get("QE_KEY", "")


def prompt_text(lines):
    out = []
    for i in range(1, lines + 1):
        node = 200 + (i * 7) % 97
        temp = 40 + (i * 13) % 40
        duty = 30 + (i * 11) % 60
        out.append("Event %04d: the sensor at node %d reported %d.1 degrees and the fan duty rose to "
                   "%d%%. Log it and continue." % (i, node, temp, duty))
    out.append("Using the log above, answer these three questions in order, with no preamble: "
               "What temperature did Event 0137 report? Which node does Event 0042 belong to? "
               "What fan duty does Event 0111 report?")
    return "\n".join(out)


def main():
    label = sys.argv[1] if len(sys.argv) > 1 else "arm"
    lines = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    max_tokens = int(sys.argv[3]) if len(sys.argv) > 3 else 512
    effort = os.environ.get("PARITY_EFFORT", "off")
    payload = {"model": MODEL, "messages": [{"role": "user", "content": prompt_text(lines)}],
               "max_tokens": max_tokens, "temperature": 0, "reasoning_effort": effort, "stream": True}
    req = urllib.request.Request(BASE + "/v1/chat/completions", data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json",
                                          "Authorization": "Bearer " + api_key()})
    content, reasoning, usage, finish = [], [], {}, None
    t0 = time.time()
    with urllib.request.urlopen(req, timeout=900) as r:
        for raw in r:
            line = raw.decode("utf-8", "replace").strip()
            if not line.startswith("data:"):
                continue
            data = line[5:].strip()
            if data == "[DONE]":
                break
            try:
                obj = json.loads(data)
            except json.JSONDecodeError:
                continue
            if obj.get("usage"):
                usage = obj["usage"]
            for ch in obj.get("choices") or []:
                d = ch.get("delta") or {}
                if d.get("reasoning_content"):
                    reasoning.append(d["reasoning_content"])
                if d.get("content"):
                    content.append(d["content"])
                if ch.get("finish_reason"):
                    finish = ch["finish_reason"]
    text = "".join(content)
    rsn = "".join(reasoning)
    host = subprocess.run(["python3", "-c",
                           "import socket;print(socket.gethostname())"], capture_output=True,
                          text=True).stdout.strip()
    print("parity label=%s host=%s effort=%s lines=%d max_tokens=%d  %.1fs"
          % (label, host, effort, lines, max_tokens, time.time() - t0))
    print("  finish=%s  prompt=%s  completion=%s  draft_n=%s  accepted=%s"
          % (finish, usage.get("prompt_tokens"), usage.get("completion_tokens"),
             usage.get("draft_n"), usage.get("draft_n_accepted")))
    print("  text_sha=%s  text_chars=%d" % (hashlib.sha256(text.encode()).hexdigest()[:16], len(text)))
    print("  reasoning_sha=%s  reasoning_chars=%d"
          % (hashlib.sha256(rsn.encode()).hexdigest()[:16], len(rsn)))
    print("  text_first_120=%r" % (text[:120],))
    return 0


if __name__ == "__main__":
    sys.exit(main())
